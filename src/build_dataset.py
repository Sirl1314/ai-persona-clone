#!/usr/bin/env python3
"""Build a ShareGPT-format training set from exported chat logs.

This is the shape of the pipeline, not the private data. Input is a plain
JSONL of messages (one per line); output is the conversations list expected by
LLaMA-Factory.

What the cleaning does, in order:
  1. drop system / advertisement / red-packet messages
  2. mask real names, phone numbers, addresses
  3. rebuild multi-turn context (keep the last K turns before each reply)
  4. drop turns where the reply is a bare sticker or a single punctuation mark
  5. tag each reply with a behavioural dimension

Usage:
    python src/build_dataset.py --input logs.jsonl --output train_sharegpt.json
"""
import argparse
import json
import re
from pathlib import Path

# Messages that are generated by the client, not by a person.
DROP_PATTERNS = (
    "撤回了一条消息",
    "对方正在输入",
    "加入了群聊",
    "[广告]",
    "领取了你的红包",
)

# Mask before anything else leaves the machine.
PHONE = re.compile(r"1[3-9]\d{9}")
AT_ALL = re.compile(r"@\S+\s?")
NAME_DICT = {}  # filled from a private mapping file; never shipped in this repo

MAX_CTX_TURNS = 6      # how much history a single sample carries
MIN_REPLY_LEN = 2      # drop replies shorter than this
STICKER_ONLY = re.compile(r"^[\s\W_]+$")

DIMS = {
    "互怼": ("就这", "笑死", "你懂", "呵呵", "卷", "摆烂", "菜"),
    "玩梗": ("top0", "666", "邪恶人格", "我的发", "离谱", "绷不住"),
    "活泼": ("哈哈哈", "笑死", "嘿嘿", "冲", "起飞"),
    "关心": ("早点", "注意", "别累", "歇", "吃了吗", "别熬"),
    "询问": ("吗？", "？", "咋", "怎么", "为啥", "啥意思"),
}


def should_drop(text: str) -> bool:
    if not text:
        return True
    if any(p in text for p in DROP_PATTERNS):
        return True
    if STICKER_ONLY.match(text):
        return True
    return False


def mask(text: str) -> str:
    text = PHONE.sub("[电话]", text)
    text = AT_ALL.sub("", text)
    for real, alias in NAME_DICT.items():
        text = text.replace(real, alias)
    return text.strip()


def classify(reply: str) -> list[str]:
    hits = [dim for dim, keys in DIMS.items() if any(k in reply for k in keys)]
    return hits or ["日常"]


def build(rows: list[dict]) -> list[dict]:
    """Group consecutive messages into conversations and split into samples."""
    conversations = []          # raw grouped conversations
    current = []
    for row in rows:
        text = mask(row.get("text", ""))
        if should_drop(text):
            continue
        if row.get("role") not in ("human", "gpt"):
            continue
        # a long silence starts a new conversation
        current.append({"from": row["role"], "value": text, "ts": row.get("ts", 0)})
        if len(current) > 40:
            conversations.append(current)
            current = []
    if current:
        conversations.append(current)

    samples = []
    for conv in conversations:
        # walk through and cut a sample at every assistant reply
        for i, turn in enumerate(conv):
            if turn["from"] != "gpt":
                continue
            history = conv[max(0, i - MAX_CTX_TURNS * 2):i]
            if not history or history[-1]["from"] != "human":
                continue
            if len(turn["value"]) < MIN_REPLY_LEN:
                continue
            msgs = [{"from": t["from"], "value": t["value"]} for t in history] + [
                {"from": "gpt", "value": turn["value"]}
            ]
            samples.append({
                "conversations": msgs,
                "dims": classify(turn["value"]),
                "ctx_turns": len(history) // 2,
            })
    return samples


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True)
    ap.add_argument("--output", required=True)
    args = ap.parse_args()

    rows = [json.loads(l) for l in Path(args.input).read_text(encoding="utf-8").splitlines() if l.strip()]
    samples = build(rows)
    Path(args.output).write_text(json.dumps(samples, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(rows)} messages -> {len(samples)} samples")

    from collections import Counter
    dim_counts = Counter(d for s in samples for d in s["dims"])
    for dim, c in dim_counts.most_common():
        print(f"  {dim}: {c}")


if __name__ == "__main__":
    main()
